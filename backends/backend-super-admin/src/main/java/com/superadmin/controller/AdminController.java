    @GetMapping("/analytics")
    public ResponseEntity<?> getAnalytics() {
        Map<String, Object> analytics = new HashMap<>();
        
        // Dynamic demand routes analytics
        List<Map<String, Object>> popularRoutes = new ArrayList<>();
        routeRepository.findAll().forEach(r -> {
            Map<String, Object> rMap = new HashMap<>();
            rMap.put("route", r.getStartPoint() + " ➔ " + r.getEndPoint());
            rMap.put("demand", r.getDemandLevel());
            rMap.put("utilization", Math.round(((double)(r.getTotalSeats() - r.getAvailableSeats()) / r.getTotalSeats()) * 100) + "%");
            popularRoutes.add(rMap);
        });
        
        // Sorting by utilization
        analytics.put("popularRoutes", popularRoutes);
        
        // Seat details
        int totalSeats = routeRepository.findAll().stream().mapToInt(Route::getTotalSeats).sum();
        int availableSeats = routeRepository.findAll().stream().mapToInt(Route::getAvailableSeats).sum();
        analytics.put("emptySeats", availableSeats);
        analytics.put("totalSeats", totalSeats);
        analytics.put("vehicleUtilization", totalSeats > 0 ? ((totalSeats - availableSeats) * 100) / totalSeats : 0);

        return ResponseEntity.ok(analytics);
    }

