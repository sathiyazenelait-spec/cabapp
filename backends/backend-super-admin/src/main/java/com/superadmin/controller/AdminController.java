    @GetMapping("/routes/search")
    public ResponseEntity<List<Map<String, Object>>> searchRoutes(
            @RequestParam(required = false) String origin,
            @RequestParam(required = false) String destination,
            @RequestParam(required = false) String institution,
            @RequestParam(required = false) String date,
            @RequestParam(required = false) String time) {
        
        List<Route> routes = routeRepository.findAll();
        List<Map<String, Object>> results = new ArrayList<>();
        
        for (Route route : routes) {
            if (origin != null && !origin.isEmpty() && !route.getStartPoint().toLowerCase().contains(origin.toLowerCase())) {
                continue;
            }
            if (destination != null && !destination.isEmpty() && !route.getEndPoint().toLowerCase().contains(destination.toLowerCase())) {
                continue;
            }
            if (institution != null && !institution.isEmpty() && !route.getEndPoint().toLowerCase().contains(institution.toLowerCase())) {
                continue;
            }
            if (!"ACTIVE".equalsIgnoreCase(route.getStatus())) {
                continue;
            }
            
            Map<String, Object> map = new HashMap<>();
            map.put("route", route);
            
            if (route.getAssignedVehicleId() != null) {
                vehicleRepository.findById(route.getAssignedVehicleId()).ifPresent(v -> {
                    map.put("vehicle", v);
                });
            }
            
            if (route.getAssignedDriverId() != null) {
                driverRepository.findById(route.getAssignedDriverId()).ifPresent(d -> {
                    map.put("driver", d);
                });
            }
            
            List<Stop> stops = stopRepository.findByRouteIdOrderBySequenceAsc(route.getId());
            map.put("stops", stops);
            
            results.add(map);
        }
        
        return ResponseEntity.ok(results);
    }

