    @PutMapping("/drivers/{id}/kyc-status")
    public ResponseEntity<?> updateDriverKycStatus(
            @PathVariable Long id, 
            @RequestParam String status,
            @RequestParam(required = false, defaultValue = "Approved by Super Admin KYC desk") String remarks) {
        
        Optional<Driver> op = driverRepository.findById(id);
        if (op.isPresent()) {
            Driver d = op.get();
            if ("APPROVED".equalsIgnoreCase(status) || "VERIFIED".equalsIgnoreCase(status)) {
                d.setStatus("ACTIVE");
            } else if ("REJECTED".equalsIgnoreCase(status)) {
                d.setStatus("SUSPENDED");
            }
            driverRepository.save(d);
        }

        Map<String, Object> resp = new HashMap<>();
        resp.put("driverId", id);
        resp.put("kycStatus", status.toUpperCase());
        resp.put("remarks", remarks);
        resp.put("updatedAt", java.time.LocalDateTime.now().toString());
        resp.put("message", "Driver KYC status updated to " + status.toUpperCase());
        return ResponseEntity.ok(resp);
    }

